"""Real requests through the provider stack, because mocks cannot see this layer.

Every ``acompletion`` in the unit suite is mocked and the wire-format baseline is
generated by the code it checks, so "the id we send is right" is a closed loop:
it asserts the string equals the string that was recorded. A green unit suite
therefore says nothing about the wire, which is what this file is for.

So this file sends. It is opt-in: without a key every test skips, and it is not
part of the default run (``tests/integration`` is excluded from ``uv run pytest``
by ``norecursedirs``). Run it deliberately::

    OPENROUTER_API_KEY=... uv run pytest tests/integration/test_provider_real_llm.py -v

What it covers is the matrix the mocked tests structurally cannot:

* the gateway routing shapes -- a prefixed id through the gateway, and a bare
  id resolved by the pin;
* the cache-breakpoint rule, as the token counts the vendor actually billed;
* the learned downgrade for an upstream that refuses the field;
* the credential probe, against a live endpoint rather than a mock transport.

Costs a handful of cheap completions per run, capped at 16 output tokens each.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

from raven.providers.base import GenerationSettings
from raven.providers.litellm_provider import LiteLLMProvider

pytestmark = pytest.mark.asyncio


def _config_key(provider: str) -> str:
    """A key from the user's own config, so a configured machine needs no env."""
    path = Path.home() / ".raven" / "config.json"
    try:
        section = json.loads(path.read_text(encoding="utf-8")).get("providers", {}).get(provider) or {}
    except Exception:
        return ""
    return section.get("apiKey") or section.get("api_key") or ""


OPENROUTER_KEY = os.environ.get("OPENROUTER_API_KEY") or _config_key("openrouter")

requires_openrouter = pytest.mark.skipif(not OPENROUTER_KEY, reason="no OpenRouter credential (env or ~/.raven)")

#: Long enough to clear every vendor's minimum cacheable prefix.
FILLER = "You are a meticulous release engineer. Track every constraint stated below and never restate it. " * 420

ANTHROPIC_MODEL = "openrouter/anthropic/claude-fable-5"
NON_ANTHROPIC_MODEL = "openrouter/google/gemini-3.5-flash"
#: OpenRouter routes this one to Amazon Bedrock, whose dialect is `cachePoint`.
REFUSING_MODEL = "openrouter/anthropic/claude-3-haiku"


def _provider(model: str, *, provider_name: str = "openrouter") -> LiteLLMProvider:
    client = LiteLLMProvider(api_key=OPENROUTER_KEY, default_model=model, provider_name=provider_name)
    client.generation = GenerationSettings(temperature=0, max_tokens=16, timeout=120)
    return client


def _messages(prompt: str = "Reply with the single word: ready.") -> list[dict]:
    return [{"role": "system", "content": FILLER}, {"role": "user", "content": prompt}]


async def _marked(model: str) -> tuple[list[dict], list[dict] | None]:
    """The payload as production sends it -- through the strategy that marks it."""
    from raven.token_wise.cache_optimizer import CacheOptimizer

    messages, tools, _ = await CacheOptimizer().before_llm_call(_messages(), None, model)
    return messages, tools


def _cached(response) -> int:
    usage = response.usage or {}
    return int(usage.get("cache_read_input_tokens") or usage.get("cached_tokens") or 0)


