# The streaming path, which is the one the TUI uses
# ---------------------------------------------------------------------------


@requires_openrouter
async def test_the_streaming_path_learns_the_refusal_too():
    """The learned downgrade lives in two places because the turn does.

    ``chat_with_retry`` covers the non-streaming callers; the TUI streams, and
    that path has no retry ladder at all -- a downgrade learned only behind the
    retry ladder never fires for the main interactive surface, and the affected
    model goes on answering 400 on every turn there.
    """
    from raven.providers import prompt_cache

    prompt_cache.reset_suppressions()
    client = _provider(REFUSING_MODEL)

    for turn in range(2):
        messages, tools = await _marked(REFUSING_MODEL)
        chunks = 0
        async for _ in client.chat_stream(messages=messages, tools=tools, model=REFUSING_MODEL, max_tokens=16):
            chunks += 1
        assert chunks, f"turn {turn} streamed nothing"

    assert prompt_cache.is_suppressed(REFUSING_MODEL)


@requires_openrouter
async def test_a_stream_that_completes_normally_still_yields_content():
    """The refusal retry reshaped the stream prologue; this is the plain path
    it must not disturb."""
    client = _provider(ANTHROPIC_MODEL)

    text = []
    async for delta in client.chat_stream(
        messages=[{"role": "user", "content": "Reply with the single word: ready."}],
        model=ANTHROPIC_MODEL,
        max_tokens=16,
    ):
        if delta.content:
            text.append(delta.content)

    assert "".join(text).strip(), "the stream produced no content"
