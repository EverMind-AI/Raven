@requires_openrouter
async def test_an_anthropic_model_still_gets_its_cache_hit():
    """The half of the rule that must not regress.

    Marking is worth keeping for this family: with the field, the second turn
    reads nearly the whole prompt back from cache; without it, nothing is
    cached. A change that stops marking here is a change to a real bill.
    """
    client = _provider(ANTHROPIC_MODEL)
    messages, tools = await _marked(ANTHROPIC_MODEL)

    first = await client.chat_with_retry(messages=messages, tools=tools, model=ANTHROPIC_MODEL)
    assert first.finish_reason != "error", first.content
    second = await client.chat_with_retry(messages=messages, tools=tools, model=ANTHROPIC_MODEL)

    assert _cached(second) > 0, "the marked prefix was not read back from cache"


@requires_openrouter
async def test_a_non_anthropic_model_is_billed_the_same_marked_or_not():
    """The half of the rule that was costing money.

    OpenRouter accepts the field on every model it serves and forwards it to
    vendors that do not read it: a breakpoint on the last conversation message
    billed Gemini for nearly double the prompt tokens the same prompt costs
    unmarked. Marked and unmarked must now be indistinguishable, because the
    marker no longer fires for this family.
    """
    client = _provider(NON_ANTHROPIC_MODEL)
    marked_messages, marked_tools = await _marked(NON_ANTHROPIC_MODEL)

    assert "cache_control" not in str(marked_messages), "the strategy marked a family that does not read it"

    marked = await client.chat_with_retry(messages=marked_messages, tools=marked_tools, model=NON_ANTHROPIC_MODEL)
    plain = await client.chat_with_retry(messages=_messages(), model=NON_ANTHROPIC_MODEL)

    assert marked.usage.get("prompt_tokens") == plain.usage.get("prompt_tokens"), (
        f"marked={marked.usage} plain={plain.usage} -- the field is still reaching the vendor"
    )


@requires_openrouter
async def test_an_upstream_that_refuses_the_field_is_learned_from_once():
    """The failure no table could have predicted.

    Both catalogues correctly report that this model caches; what neither says is
    that OpenRouter routes it to Amazon Bedrock, whose dialect is ``cachePoint``.
    It answered 400 every turn. The first turn now pays one extra request and
    every turn after it is clean.
    """
    from raven.providers import prompt_cache

    prompt_cache.reset_suppressions()
    client = _provider(REFUSING_MODEL)

    for turn in range(3):
        messages, tools = await _marked(REFUSING_MODEL)
        response = await client.chat_with_retry(messages=messages, tools=tools, model=REFUSING_MODEL)
        assert response.finish_reason != "error", f"turn {turn}: {response.content}"

    assert prompt_cache.is_suppressed(REFUSING_MODEL), "the refusal was not learned"


