async def test_a_provider_with_no_catalogue_endpoint_is_not_called_unconfigured(tmp_path):
    """Runs without any credential: the point is what the probe *says*, and it
    said `not_configured` for seven providers that were configured correctly."""
    from raven.config.update_providers import set_provider_fields
    from raven.config.update_providers import test_provider as probe

    config = tmp_path / "config.json"
    set_provider_fields("anthropic", {"api_key": "sk-probe"}, config_path=config)

    result = probe("anthropic", timeout_s=10, config_path=config)

    assert result["status"] == "no_probe_endpoint", result


