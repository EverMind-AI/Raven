@requires_openrouter
async def test_a_gateway_routed_id_reaches_the_upstream_vendor():
    """The prefix names the gateway, the rest names the vendor behind it."""
    response = await _provider(ANTHROPIC_MODEL).chat_with_retry(messages=_messages(), model=ANTHROPIC_MODEL)

    assert response.finish_reason != "error", response.content
    assert response.usage.get("prompt_tokens")


@requires_openrouter
async def test_a_bare_id_under_a_gateway_still_routes():
    """A stored id can be bare when the provider is pinned; the wire form has to
    put the gateway's prefix back on, or the request goes to the vendor direct
    with the gateway's key."""
    client = _provider(ANTHROPIC_MODEL)
    response = await client.chat_with_retry(messages=_messages(), model="anthropic/claude-fable-5")

    assert response.finish_reason != "error", response.content


@requires_openrouter
async def test_the_id_that_goes_out_is_the_one_wire_builds():
    """Asserted against the live call rather than against a recorded string.

    The baseline file is generated by the same code it checks, so it can only say
    the behaviour did not change -- never that it is right. A request that comes
    back at all is the vendor confirming the id resolved.
    """
    from raven.providers.wire import wire_model

    client = _provider(ANTHROPIC_MODEL)
    sent = client._resolve_model(ANTHROPIC_MODEL)

    assert sent == wire_model(ANTHROPIC_MODEL, gateway=client._gateway)
    response = await client.chat_with_retry(messages=_messages(), model=ANTHROPIC_MODEL)
    assert response.finish_reason != "error", response.content


