"""Multimodal generation tools (OpenRouter backend).

OpenRouter exposes chat-routed generation through the OpenAI-compatible
chat-completions API with extra *output modalities*; speech and the chat-routed
image models POST to ``{base}/chat/completions`` with a ``modalities`` array
and read the generated bytes back from the assistant message:

- ``image_generate``  → ``modalities:["image","text"]`` → ``message.images[].image_url.url``
  (a ``data:image/...;base64,...`` URI). Default model ``openai/gpt-image-2.5-sunburst``
  with provider-default quality. Dedicated image models
  (``gpt-image-*``) are served only by the Images API and answer 404 on
  chat/completions however the modalities are spelled, so they go to
  ``POST {base}/images`` on OpenRouter (``input_references`` carries the edit
  inputs) and to ``/images/generations`` / ``/images/edits`` on an
  OpenAI-compatible base -- by name, and as the fallback when chat/completions
  refuses a model as image-only.
- ``text_to_speech``  → ``modalities:["audio","text"]`` + ``audio:{voice,format}``.
  OpenRouter only returns audio when ``stream:true`` AND only as raw ``pcm16``
  in that mode, so we stream, concatenate the base64 ``delta.audio.data`` chunks,
  and wrap the PCM (24 kHz / mono / 16-bit) into a WAV with the stdlib ``wave``
  module — zero binary dependency. mp3/opus/flac are transcoded from that WAV
  only when ``ffmpeg`` is on PATH; otherwise we keep the WAV and say so.
  Default model ``openai/gpt-audio-mini``.

Video uses a separate async endpoint (NOT chat-completions):

- ``video_generate``  → ``POST {base}/videos`` with ``{model, prompt}`` → ``202``
  ``{id, polling_url, status}`` → poll ``polling_url`` until ``completed`` (URLs
  to download) or ``failed`` (with ``error``). Default model
  ``kwaivgi/kling-v3.0-std`` (Kling v3 Standard). Requires postpaid billing /
  credits enabled on the OpenRouter account.

Generated files are written under ``<working directory>/<output_subdir>`` --
``workdir.current()`` when a turn is bound, the constructor's root otherwise --
and the path is returned so the agent can forward it with the ``message``
tool's ``media`` field. A denied request (HTTP 403) hints at setting ``tools.media.proxy``.

See demos/skill_retrieval/skills/image-gen/SKILL.md for the image recipe.
"""

