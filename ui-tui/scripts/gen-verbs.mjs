#!/usr/bin/env node
// Raven ticker-verb codegen.
//
// Reads the repo-level `ui-shared/verbs.json` (single source of truth, shared
// with the GUI, which imports the same file at build time) and emits
// `ui-tui/src/content/verbs.generated.ts`. Generated rather than imported so
// the TUI keeps `rootDir: src` and ships one self-contained bundle.
//
// Usage:
//   node scripts/gen-verbs.mjs            # write verbs.generated.ts
//   node scripts/gen-verbs.mjs --check    # exit 1 when the checked-in file
//                                         # is stale (CI lint mode)

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const SOURCE = resolve(here, '../../ui-shared/verbs.json')
const TARGET = resolve(here, '../src/content/verbs.generated.ts')

const header = `// GENERATED by scripts/gen-verbs.mjs from ui-shared/verbs.json -- do not edit.
// Run \`npm run gen:verbs\` after changing the catalogue.
`

const render = spec => {
  const verbs = spec.verbs.map(v => `  '${v}'`).join(',\n')
  return `${header}
export const VERB_ROTATION_MS = ${spec.rotationMs}

export const VERBS = [
${verbs}
]
`
}

const main = async () => {
  const spec = JSON.parse(await readFile(SOURCE, 'utf8'))
  const text = render(spec)

  if (process.argv.includes('--check')) {
    const current = await readFile(TARGET, 'utf8').catch(() => '')
    if (current !== text) {
      console.error('verbs.generated.ts is stale -- run `npm run gen:verbs`')
      process.exit(1)
    }
    return
  }

  await writeFile(TARGET, text)
  console.log(`wrote ${TARGET}`)
}

await main()
