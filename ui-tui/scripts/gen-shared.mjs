#!/usr/bin/env node
// Raven shared-catalogue codegen.
//
// Reads the repo-level catalogues under `ui-shared/` (single source of truth,
// shared with the GUI, which imports the same files at build time) and emits
// their TypeScript projections under `ui-tui/src/content/`. Generated rather
// than imported so the TUI keeps `rootDir: src` and ships one self-contained
// bundle.
//
// Usage:
//   node scripts/gen-shared.mjs            # write the projections
//   node scripts/gen-shared.mjs --check    # exit 1 when any projection is stale

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))

const header = source => `// GENERATED by scripts/gen-shared.mjs from ui-shared/${source} -- do not edit.
// Run \`npm run gen:shared\` after changing the catalogue.
`

const CATALOGUES = [
  {
    source: 'verbs.json',
    target: '../src/content/verbs.generated.ts',
    render: spec => `${header('verbs.json')}
export const VERB_ROTATION_MS = ${spec.rotationMs}

export const VERBS = [
${spec.verbs.map(v => `  '${v}'`).join(',\n')}
]
`
  },
  {
    source: 'charms.json',
    target: '../src/content/charms.generated.ts',
    render: spec => `${header('charms.json')}
export const LONG_RUN_CHARMS = [
${spec.charms.map(c => `  '${c}'`).join(',\n')}
]
`
  }
]

const read = async file => JSON.parse(await readFile(resolve(here, '../../ui-shared', file), 'utf8'))

const main = async () => {
  const check = process.argv.includes('--check')
  const stale = []

  for (const catalogue of CATALOGUES) {
    const text = catalogue.render(await read(catalogue.source))
    const target = resolve(here, catalogue.target)

    if (check) {
      const current = await readFile(target, 'utf8').catch(() => '')
      if (current !== text) {
        stale.push(catalogue.target)
      }
    } else {
      await writeFile(target, text)
      console.log(`wrote ${target}`)
    }
  }

  if (stale.length) {
    console.error(`${stale.join(', ')} stale -- run \`npm run gen:shared\``)
    process.exit(1)
  }
}

await main()
